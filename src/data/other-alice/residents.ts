export const otherAliceResidents = records.map((record) => {
  const asset = getOtherAliceAsset(record.assetRef);
  const landscapeAsset = getOtherAliceAsset(record.landscapeAssetRef);
  return {
    ...record,
    image: asset?.publicPath,
    imageAlt: asset?.altText,
    landscapeImage: landscapeAsset?.publicPath,
    landscapeImageAlt: landscapeAsset?.altText,
  };
});

export const publicOtherAliceCast = otherAliceResidents.filter(
  (record) => record.visibility === "public" && record.publicState !== "withheld",
);

const previewIds = ["other-alice", "chester", "ciryl-spade", "queen-of-hearts"];
export const otherAliceCastPreview = previewIds
  .map((id) => publicOtherAliceCast.find((record) => record.id === id))
  .filter((record): record is NonNullable<typeof record> => Boolean(record));

export function getOtherAliceResident(id: string) {
  return otherAliceResidents.find((resident) => resident.id === id);
}
