const entityById = new Map(editorialEntities.map((entity) => [entity.id, entity]));

export function getEditorialEntity(id: string): EditorialEntity | undefined {
  return entityById.get(id);
}

export function normalizeEditorialAlias(value: string): string {
  return value.trim().toLocaleLowerCase("en-US").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

export function articleUsesSeries(
  data: { mesh?: { series?: string[] } },
  seriesId: EditorialSeriesId | string,
): boolean {
  return data.mesh?.series?.includes(seriesId) ?? false;
}
